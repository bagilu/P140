import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {validateNetwork} from '../dist/core.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const data=path.join(root,'dist/data');
const manifest=JSON.parse(fs.readFileSync(path.join(data,'manifest.json'),'utf8'));
const files=manifest.routes.map(item=>{const p=path.resolve(data,item.file);if(!p.startsWith(data+path.sep))throw Error('路線檔路徑超出 data');const doc=JSON.parse(fs.readFileSync(p,'utf8'));if(doc.routes.length!==1||doc.routes[0].routeId!==item.routeId)throw Error('索引與路線檔不符');return doc;});
if(!files.length)throw Error('索引沒有路線');const base=files[0];
for(const doc of files)for(const key of ['schemaVersion','dataVersion','timezone','generatedAt','displaySettings'])if(JSON.stringify(doc[key])!==JSON.stringify(base[key]))throw Error(`不同發布批次或設定：${key}`);
if(manifest.schemaVersion!==base.schemaVersion||manifest.dataVersion!==base.dataVersion)throw Error('索引版本不符');
const result={...base,isDemo:files.some(f=>f.isDemo||f.routes[0].isDemo),routes:files.flatMap(f=>f.routes)};
const errors=validateNetwork(result);if(errors.length)throw Error(errors.join('\n'));
fs.writeFileSync(path.join(data,'bus_network.json'),JSON.stringify(result));console.log(`Merged ${result.routes.length} routes; references and simulation invariants passed.`);
